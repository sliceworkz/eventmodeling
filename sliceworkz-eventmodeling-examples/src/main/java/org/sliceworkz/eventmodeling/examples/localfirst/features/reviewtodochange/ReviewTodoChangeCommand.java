package org.sliceworkz.eventmodeling.examples.localfirst.features.reviewtodochange;

import org.sliceworkz.eventmodeling.commands.BusinessException;
import org.sliceworkz.eventmodeling.commands.Command;
import org.sliceworkz.eventmodeling.commands.CommandContext;
import org.sliceworkz.eventmodeling.examples.localfirst.TodoListDomain;
import org.sliceworkz.eventmodeling.examples.localfirst.TodoListDomain.TodoEvent;
import org.sliceworkz.eventmodeling.examples.localfirst.TodoListDomain.TodoEvent.TodoChangeReviewed;
import org.sliceworkz.eventmodeling.examples.localfirst.TodoListDomain.TodoId;
import org.sliceworkz.eventmodeling.examples.localfirst.TodoListDomain.Verdict;
import org.sliceworkz.eventmodeling.examples.localfirst.crdt.OperationStamp;
import org.sliceworkz.eventmodeling.examples.localfirst.crdt.ReplicaId;
import org.sliceworkz.eventmodeling.examples.localfirst.features.replicastate.ReplicaStateDecisionModel;

/**
 * A reviewer decides about an honest change that was made on compromised input and no longer holds
 * without it: it stands ({@code CONFIRMED}), or it is left out of the to-do list everywhere ({@code
 * REVERTED}). Two reviewers deciding differently without knowing it: revert wins.
 */
public record ReviewTodoChangeCommand ( ReplicaId replica, TodoId todoId, String operationId, Verdict verdict ) implements Command<TodoEvent> {

	@Override
	public void execute ( CommandContext<TodoEvent, TodoEvent> context ) {
		var state = new ReplicaStateDecisionModel();
		var result = context.decisionModels(state);

		BusinessException.when(verdict == null, "A review confirms or reverts");
		BusinessException.when(!state.pendingReview(todoId, operationId), "Change " + operationId + " is not awaiting review");

		OperationStamp stamp = state.nextStamp(replica);
		result.raiseEvent(new TodoChangeReviewed(todoId, operationId, verdict, stamp),
				TodoListDomain.tagsOf(todoId, replica), stamp.operationId());
	}

}
